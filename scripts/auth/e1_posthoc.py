#!/usr/bin/env python3
"""AUTH-E1 post-hoc analyses requested in the ChatGPT round-2 review (docs/auth/discussion_20261124/ROUND2_ChatGPT_outline.md),
written after the one-time E1 test read; the E1 STOP verdict is not re-decided here.  Frozen models only, no refit.

G8  zero-training baseline: the kept end with the highest QuantSeq signal (feature log_quant_signal = log1p of the max
    over the three replicates); ties -> nearest.
G9  high-quality molecule labels: MAPQ >= 30, soft clip <= 30 nt at each end, TALON fA (fraction A downstream) <= 0.5;
    each read assigned to at most one candidate end (the nearest within +-100 bp); groups rebuilt with the same rules
    (>= 1 end with >= 2 reads, >= 1 end with 0, cov >= 10); ends with exactly 1 read counted separately.
G10 signal-matched hard pairs: same TSS, one supported end (>= 2) and one zero-link end, QuantSeq signals within 2x,
    ends > 200 bp apart, cov >= 30; pairwise accuracy of G8 / E2 / E3 / E4 (higher score on the supported end).
G11 the same candidates at locus level: S50 match to an AUTH truth lnc locus vs molecule support; what the frozen AUTH
    model (E3) and E2 pick.
Also: per-chromosome group statistics (groups, candidates, supported ends, depth, top-2 signal ratio).
  e1_posthoc.py -> outputs/AUTH_E1/POSTHOC.json   (train and test chromosomes; test labels already generated by e1_score)
"""
import json
import os
import re
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import auth_lib as A                       # noqa: E402
import e1_labels as EL                     # noqa: E402
import e1_dev as ED                        # noqa: E402

A.open_test()
CIG = re.compile(r"(\d+)([MIDNSHP=X])")
W = 100
M = json.load(open(f"{EL.OUT}/dev/MODEL_E1.json"))
AUTHM = json.load(open(f"{A.OUT}/dev/MODEL.json"))["true_vs_wrong"]
SIG = A.FI["log_quant_signal"]


def hq_reads(c):
    out = {"+": ([], []), "-": ([], [])}
    p = subprocess.Popen([EL.SAMTOOLS, "view", "-F", "2308", "-q", "30", EL.BAM, c], stdout=subprocess.PIPE, text=True)
    for line in p.stdout:
        f = line.rstrip("\n").split("\t")
        flag, pos, cig = int(f[1]), int(f[3]), CIG.findall(f[5])
        fa = next((float(t[5:]) for t in f[11:] if t.startswith("fA:f:")), 0.0)
        if fa > 0.5:
            continue
        if (cig[0][1] == "S" and int(cig[0][0]) > 30) or (cig[-1][1] == "S" and int(cig[-1][0]) > 30):
            continue
        end = pos + sum(int(n) for n, op in cig if op in "MDN=X") - 1
        if flag & 16:
            out["-"][0].append(end)
            out["-"][1].append(pos)
        else:
            out["+"][0].append(pos)
            out["+"][1].append(end)
    assert p.wait() == 0
    res = {}
    for st, (a, b) in out.items():          # sort by 5' end (fix 2026-11-24: minus-strand 5' ends are not sorted)
        a, b = np.asarray(a, np.int64), np.asarray(b, np.int64)
        o = np.argsort(a, kind="stable")
        res[st] = (a[o], b[o])
        assert np.all(res[st][0][:-1] <= res[st][0][1:])
    return res


def scores(g):
    return {"G8": g["X"][:, SIG] - 1e-6 * g["rank"], "E2": ED.score_clogit(M["E2"], g), "E3": A.logit(AUTHM, g["X"]),
            "E4": ED.score_clogit(M["E4"], g)}


def hq_groups(c, R):
    """Groups under the G9 labels (unique nearest-end assignment)."""
    z = np.load(f"{A.OUT}/pairs/{c}.npz")
    keep = z["X"][:, A.FI["pc_same"]] == 0
    key = z["strand"].astype(np.int64) * 10 ** 9 + z["row"]
    G, n1 = [], 0
    for k in np.unique(key[keep]):
        idx = np.nonzero((key == k) & keep)[0]
        st = A.STR[int(z["strand"][idx[0]])]
        t = int(z["tss"][idx[0]])
        five, three = R[st]
        lo, hi = np.searchsorted(five, t - W, "left"), np.searchsorted(five, t + W, "right")
        th = three[lo:hi]
        if len(th) < EL.MIN_COV:
            continue
        ends = z["endpos"][idx]
        d = np.abs(th[:, None] - ends[None, :])
        best = d.argmin(1)
        ok = d[np.arange(len(th)), best] <= W
        cnt = np.bincount(best[ok], minlength=len(idx))
        if (cnt >= 2).any() and (cnt == 0).any():
            n1 += int((cnt == 1).sum())
            G.append({"X": z["X"][idx], "rank": z["rank"][idx], "y": cnt >= 2, "cnt": cnt, "chrom": c,
                      "s": int(z["s"][idx[0]]), "ends": ends, "cov": len(th)})
    return G, n1


def top1_table(G):
    if not G:
        return {"n": 0}
    out = {"n": len(G), "random": float(np.mean([g["y"].mean() for g in G]))}
    for m in ("G8", "E2", "E3", "E4"):
        out[m] = float(np.mean([g["y"][int(np.argmax(scores(g)[m]))] for g in G]))
    out["E0"] = float(np.mean([g["y"][ED.pick_e0(g, M["E0_K"])] for g in G]))
    return out


def hard_pairs(G, min_cov=30):
    acc = {m: [] for m in ("G8", "E2", "E3", "E4")}
    for g in G:
        if g.get("cov", 1e9) < min_cov:
            continue
        sig = np.expm1(g["X"][:, SIG])
        sc = scores(g)
        pos = np.nonzero(g["y"])[0]
        neg = np.nonzero(g["cnt"] == 0)[0] if "cnt" in g else np.nonzero(~g["y"])[0]
        for i in pos:
            for j in neg:
                a, b = max(sig[i], 1e-9), max(sig[j], 1e-9)
                if max(a, b) / min(a, b) <= 2 and abs(int(g["ends"][i]) - int(g["ends"][j])) > 200:
                    for m in acc:
                        acc[m].append(float(sc[m][i] > sc[m][j]))
    return {"n_pairs": len(acc["G8"]), **{m: (float(np.mean(v)) if v else None) for m, v in acc.items()}}


def g11(c, G):
    """Candidates of the E1 groups (original labels): S50 truth match vs molecule support; picks of E2 / E3."""
    tr = A.load_truth(c)["ts"]
    tab = {"s50_and_supported": 0, "s50_not_supported": 0, "supported_not_s50": 0, "neither": 0}
    picks = {m: {"supported": 0, "s50": 0} for m in ("E2", "E3")}
    for g in G:
        s50 = np.zeros(len(g["y"]), bool)
        for j in range(len(g["y"])):
            s, e = int(g["ss"][j]), int(g["ee"][j])
            for _, st, gs, ge in tr:
                if st != g["strand"]:
                    continue
                ov = min(e, ge) - max(s, gs) + 1
                if ov > 0 and ov / (ge - gs + 1) >= 0.5 and ov / (e - s + 1) >= 0.5:
                    s50[j] = True
                    break
        y = g["y"]
        tab["s50_and_supported"] += int((s50 & y).sum())
        tab["s50_not_supported"] += int((s50 & ~y).sum())
        tab["supported_not_s50"] += int((~s50 & y).sum())
        tab["neither"] += int((~s50 & ~y).sum())
        sc = scores(g)
        for m in picks:
            k = int(np.argmax(sc[m]))
            picks[m]["supported"] += int(y[k])
            picks[m]["s50"] += int(s50[k])
    return tab, picks


def orig_groups(c, test):
    z = np.load(f"{A.OUT}/pairs/{c}.npz")
    L = dict(np.load(f"{EL.OUT}/{'labels_test' if test else 'labels'}/{c}.npz"))
    G = []
    for g in EL.groups(L, W):
        G.append({"X": z["X"][g], "rank": z["rank"][g], "y": L["link100"][g] >= 2, "cnt": L["link100"][g], "s": int(z["s"][g[0]]),
                  "ss": z["s"][g], "ee": z["e"][g], "ends": z["endpos"][g], "strand": A.STR[int(z["strand"][g[0]])], "chrom": c,
                  "cov": int(L["cov100"][g].max())})
    return G


def describe(G):
    if not G:
        return {}
    sig = [np.sort(np.expm1(g["X"][:, SIG]))[::-1] for g in G]
    return {"groups": len(G), "cand_mean": float(np.mean([len(g["y"]) for g in G])), "supported_mean": float(np.mean([g["y"].sum() for g in G])),
            "frac_single_supported": float(np.mean([g["y"].sum() == 1 for g in G])), "cov_median": float(np.median([g["cov"] for g in G])),
            "top2_signal_ratio_median": float(np.median([s[0] / max(s[1], 1e-9) for s in sig if len(s) > 1]))}


def main():
    res = {"doc": __doc__.split("  e1_posthoc.py")[0]}
    for name, chroms, test in (("train", A.TRAIN, False), ("test", A.TEST, True)):
        Go = [g for c in chroms for g in orig_groups(c, test)]
        r = {"orig_labels": top1_table(Go), "orig_hard_pairs": hard_pairs(Go),
             "per_chrom": {c: {**describe([g for g in Go if g["chrom"] == c]), **top1_table([g for g in Go if g["chrom"] == c])} for c in chroms},
             "ones_orig": int(sum(int((g["cnt"] == 1).sum()) for g in Go))}
        Gh, n1 = [], 0
        for c in chroms:
            g_, k = hq_groups(c, hq_reads(c))
            Gh += g_
            n1 += k
        r["hq_labels"] = top1_table(Gh)
        r["hq_hard_pairs"] = hard_pairs(Gh)
        r["hq_ends_with_one_read"] = n1
        if test:
            tab, picks = {}, {}
            for c in chroms:
                t_, p_ = g11(c, [g for g in Go if g["chrom"] == c])
                for k, v in t_.items():
                    tab[k] = tab.get(k, 0) + v
                for m, d in p_.items():
                    for k, v in d.items():
                        picks.setdefault(m, {}).setdefault(k, 0)
                        picks[m][k] += v
            r["G11_candidates"] = tab
            r["G11_picks"] = picks
        res[name] = r
        print(name, json.dumps({k: r[k] for k in ("orig_labels", "hq_labels", "orig_hard_pairs", "hq_hard_pairs")}), flush=True)
    json.dump(res, open(f"{EL.OUT}/POSTHOC.json", "w"), indent=1, default=float)
    print(json.dumps({k: res["test"].get(k) for k in ("G11_candidates", "G11_picks", "ones_orig", "hq_ends_with_one_read")}, indent=1))


if __name__ == "__main__":
    main()
